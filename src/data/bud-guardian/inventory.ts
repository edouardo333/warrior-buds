import type { InventoryMovement, InventoryProduct } from "@/types/inventory";

function daysAgo(days: number): string {
  return new Date(Date.now() - days * 24 * 60 * 60 * 1000).toISOString();
}

function daysFromNow(days: number): string {
  return new Date(Date.now() + days * 24 * 60 * 60 * 1000).toISOString();
}

function product(input: Omit<InventoryProduct, "createdAt" | "updatedAt"> & { receivedDaysAgo: number }): InventoryProduct {
  const { receivedDaysAgo, ...rest } = input;
  return { ...rest, createdAt: daysAgo(receivedDaysAgo), updatedAt: daysAgo(Math.min(receivedDaysAgo, 1)) };
}

